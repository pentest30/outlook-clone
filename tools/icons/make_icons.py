"""Builds src/Outlook.App/Styles/Icons.axaml from Fluent UI System Icons (MIT, Microsoft).

    python tools/icons/make_icons.py <folder of downloaded *_20_regular.svg files>

Download an icon: https://raw.githubusercontent.com/microsoft/fluentui-system-icons/main/assets/
<Name With Spaces>/SVG/ic_fluent_<snake_name>_20_regular.svg, saved as <snake_name>.svg.
Each SVG holds one or more paths; they become one StreamGeometry resource, Icon.<PascalName>.
"""
import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1])
target = pathlib.Path(__file__).resolve().parents[2] / "src/Outlook.App/Styles/Icons.axaml"

entries = []
for svg in sorted(source.glob("*.svg")):
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg.read_text(encoding="utf-8"))
    if not paths:
        continue
    key = "Icon." + "".join(part.capitalize() for part in svg.stem.split("_"))
    # F1 = nonzero fill rule, which is what the SVGs use.
    entries.append(f'  <StreamGeometry x:Key="{key}">F1 {" ".join(paths)}</StreamGeometry>')

target.write_text(
    '<!-- Generated by tools/icons/make_icons.py from Fluent UI System Icons\n'
    '     (https://github.com/microsoft/fluentui-system-icons, MIT licence, (c) Microsoft Corporation).\n'
    '     20 px "regular" outlines; draw them with PathIcon so they take the text colour. -->\n'
    '<ResourceDictionary xmlns="https://github.com/avaloniaui"\n'
    '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n'
    + "\n".join(entries) + "\n</ResourceDictionary>\n",
    encoding="utf-8")
print(f"{len(entries)} icons -> {target}")
